const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem("tls-language") || "kk");
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => {
    const changeLanguage = (nextLanguage) => {
      localStorage.setItem("tls-language", nextLanguage);
      setLanguage(nextLanguage);
      document.documentElement.lang = nextLanguage;
    };

    return { language, setLanguage: changeLanguage, t: dictionaries[language], webhookUrl: WEBHOOK_URL };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
